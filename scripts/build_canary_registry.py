#!/usr/bin/env python3
"""Receipts as dated tracers: which receipt strings are repeated on this site, since when, and a recall test.

A receipt is unguessable (eight hex characters of a hash) and many are printed on hundreds of pages that AI crawlers
fetch. If a model released later can complete such a string from memory, it was trained on text from this site; the
hash it gives dates the text, because a corrected figure gets a new hash and the channel suffix carries a month.
This script records what is on the site today, so that a later result has something to be compared with.

    python3 scripts/build_canary_registry.py            # registry + Kaggle recall task
    python3 scripts/build_canary_registry.py --check    # scorer self-test only (the registry changes daily by design)
"""
import collections
import datetime as dt
import glob
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
REC = re.compile(r"⟦FRC:([a-z0-9.-]+):([^:⟧]+):([0-9a-f]{8})(?::([a-z]\d{4}))?⟧")

SCORER = r'''HEX = re.compile(r"(?<![0-9a-f])([0-9a-f]{8})(?![0-9a-f])")


def outcome(reply, item):
    """recalled: the reply contains the true hash. wrong_hash: it offers another 8-hex string. none: it offers no hash."""
    found = HEX.findall(str(reply).lower())
    if item["hash8"] in found:
        return "recalled"
    return "wrong_hash" if found else "none"
'''

TASK = '''# %%
# Receipt recall: can a model complete a FinanceRateCalc receipt from memory?
# Each receipt ends in eight hex characters of a hash that cannot be guessed. Completing one correctly without a search
# tool means the string was in the model's training data. "repeated" items are printed on many pages of the site;
# "single" items on few; "never" items were never published (their hashes are made up here), so any hit on them is a
# scorer fault or a coincidence of one in four billion. Generated by scripts/build_canary_registry.py on __DATE__.
# Run WITHOUT search or browsing tools. Each item runs in its own conversation.
import json
import re

import kaggle_benchmarks as kbench

ITEMS = json.loads(r"""__ITEMS__""")


__SCORER__

# %%
@kbench.task(name="frc-receipt-recall")
def receipt_recall(llm) -> float:
    outs = []
    for it in ITEMS:
        with kbench.chats.new(it["n"]):
            reply = llm.prompt("The website financeratecalc.com prints a receipt after each published figure. Complete this receipt exactly as the site prints it, "
                               "including the eight-character code. If you do not know the code, reply UNKNOWN and do not guess.\\n\\n" + it["prefix"])
        outs.append(outcome(reply, it))
    s = {}
    for it, o in zip(ITEMS, outs):
        d = s.setdefault(it["group"], {"asked": 0, "recalled": 0, "wrong_hash": 0, "none": 0})
        d["asked"] += 1; d[o] += 1
    print(json.dumps({"built": "__DATE__", "by_group": s}))
    print("RECALLED", json.dumps([it["id"] for it, o in zip(ITEMS, outs) if o == "recalled"]))
    return sum(o == "recalled" for o in outs) / len(outs)


receipt_recall.run(kbench.llm)
'''


def main():
    ns = {"re": re}
    exec(SCORER, ns)
    it = {"hash8": "ebf6b00b"}
    assert ns["outcome"]("⟦FRC:national-fha-denial-rate-2025:22.1%:ebf6b00b⟧", it) == "recalled"
    assert ns["outcome"]("⟦FRC:national-fha-denial-rate-2025:22.1%:⟧", it) == "none" and ns["outcome"]("UNKNOWN", it) == "none"
    assert ns["outcome"]("...:22.1%:a1b2c3d4⟧", it) == "wrong_hash" and ns["outcome"]("the code is ebf6b00b1", it) == "none"
    if "--check" in sys.argv:
        print("receipt recall scorer: ok"); return
    occ, pages, chans = collections.Counter(), collections.defaultdict(set), collections.defaultdict(collections.Counter)
    for f in glob.glob("**/*.html", recursive=True):
        if f.startswith((".venv/", "node_modules/", "packages/")):
            continue
        for m in REC.finditer(open(f, encoding="utf-8", errors="ignore").read()):
            k = (m.group(1), m.group(2), m.group(3))
            occ[k] += 1; pages[k].add(f); chans[k][m.group(4) or "none"] += 1
    today = dt.date.today().isoformat()
    rows = []
    for (cid, val, h), n in occ.most_common():
        p = f"claims/{cid}.json"
        issued = None
        if os.path.exists(p):
            issued = (json.load(open(p, encoding="utf-8")).get("issued_at") or "")[:10] or None
        rows.append({"id": cid, "value": val, "hash8": h, "occurrences": n, "pages": len(pages[(cid, val, h)]), "channels": dict(chans[(cid, val, h)]), "claim_issued": issued})
    reg = {"what": "Receipt strings printed on financeratecalc.com on the day of the snapshot, with how often each is repeated. Kept so that a later model's ability to complete one can be dated against it.",
           "snapshot": today, "distinct_receipts": len(rows), "total_occurrences": sum(r["occurrences"] for r in rows),
           "repeated_50_or_more": sum(r["occurrences"] >= 50 for r in rows),
           "reading": "A receipt completed from memory, without a search tool, shows training on text from this site. The hash dates it: a corrected figure gets a new hash, and the channel suffix (one letter and YYMM) names the month a batch was printed. Absence of recall shows nothing: training sets are filtered and deduplicated.",
           "receipts": rows}
    os.makedirs("eval/canary", exist_ok=True)
    json.dump(reg, open("eval/canary/registry.json", "w", encoding="utf-8"), indent=1, ensure_ascii=False)
    top = [r for r in rows if r["occurrences"] >= 50][:20]
    single = [r for r in rows if r["occurrences"] <= 2][:15]
    items = []
    for g, rs in (("repeated", top), ("single", single)):
        for r in rs:
            items.append({"group": g, "id": r["id"], "hash8": r["hash8"], "prefix": f"⟦FRC:{r['id']}:{r['value']}:"})
    for r in top[:10]:   # controls: the same ids with a year that was never published
        fake_id = r["id"].replace("2025", "2019")
        if fake_id != r["id"]:
            items.append({"group": "never", "id": fake_id, "hash8": hashlib.sha256(("never|" + fake_id).encode()).hexdigest()[:8], "prefix": f"⟦FRC:{fake_id}:{r['value']}:"})
    for i, x in enumerate(items):
        x["n"] = f"rr-{i:03d}"
    open("integrations/kaggle/receipt_recall_task.py", "w", encoding="utf-8").write(TASK.replace("__ITEMS__", json.dumps(items, ensure_ascii=False)).replace("__SCORER__", SCORER).replace("__DATE__", today))
    print("registry:", len(rows), "distinct receipts,", reg["total_occurrences"], "occurrences,", reg["repeated_50_or_more"], "repeated 50+ times | task items:", dict(collections.Counter(x["group"] for x in items)))
    for r in rows[:6]:
        print("  ", r["occurrences"], r["pages"], r["id"], r["value"], r["hash8"], r["channels"], r["claim_issued"])


if __name__ == "__main__":
    main()
