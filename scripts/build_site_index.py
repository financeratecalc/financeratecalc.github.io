#!/usr/bin/env python3
"""Static index pages so every published page has at least one incoming HTML link.

Crawlers reach pages through sitemaps and llms.txt; a human-style crawl (Ahrefs, 31 Oct 2026) found 178 pages with
no incoming internal link — 165 metro pages, 20 stat pages, all 22 city pages, the reconciliation page and the
September verdict among them. This script writes:

    metro/index.html   all metro pages, grouped by state, with the figure from each page's meta description
    stat/index.html    all question pages
    city/index.html    all city affordability pages
    site-index.html    one page linking every hub and every html page not reachable from any other page

Run from the repo root; idempotent. `--check` exits 1 if the generated files differ from the committed ones.
"""
import glob
import html
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

STYLE = ("body{background:#08090c;color:#e8e4da;font-family:'DM Sans',system-ui,sans-serif;margin:0;line-height:1.6}"
         ".wrap{max-width:900px;margin:0 auto;padding:36px 18px 70px}h1{font-family:Georgia,serif;font-size:27px;color:#f5f2ea;line-height:1.25}"
         "h2{font-family:Georgia,serif;font-size:18px;color:#f5f2ea;margin-top:26px}.kicker{font-family:monospace;font-size:11px;letter-spacing:2px;color:#C8A84B;text-transform:uppercase}"
         "a{color:#C8A84B}ul{padding-left:18px;columns:2;column-gap:28px}li{break-inside:avoid;margin:3px 0;font-size:14px}.small{font-size:12.5px;opacity:.75}"
         "@media(max-width:640px){ul{columns:1}}")
NAV = ('<nav data-frc-nav="1" aria-label="Site" style="font-family:system-ui,sans-serif;font-size:12.5px;padding:8px 16px;background:#0b0d12;border-bottom:1px solid rgba(255,255,255,.08);display:flex;gap:14px;flex-wrap:wrap;align-items:center">'
       '<a href="/" style="color:#C8A84B;font-weight:700;text-decoration:none">FinanceRateCalc</a>'
       '<a href="/fha-denial-rates-top-100.html" style="color:rgba(255,255,255,.7);text-decoration:none">Lenders</a>'
       '<a href="/fha-denial-rates-by-state.html" style="color:rgba(255,255,255,.7);text-decoration:none">States</a>'
       '<a href="/fha-denial-rates-by-metro.html" style="color:rgba(255,255,255,.7);text-decoration:none">Metros</a>'
       '<a href="/answers.html" style="color:rgba(255,255,255,.7);text-decoration:none">Answers</a>'
       '<a href="/site-index.html" style="color:rgba(255,255,255,.7);text-decoration:none">Index</a></nav>')

TITLE_RX = re.compile(r"<title>([^<]*)</title>", re.I)
DESC_RX = re.compile(r'<meta name="description" content="([^"]*)"', re.I)
HREF_RX = re.compile(r'''href=["']/?([^"'#?]+\.html)["']''')
NOINDEX_RX = re.compile(r'name="robots" content="[^"]*noindex', re.I)
SKIP_DIRS = ("node_modules/", "_site/", "outputs/", "rl-env/", "evals/", "packages/", "fixtures/", "research_notes/", "reports/")


def read(p):
    return open(p, encoding="utf-8", errors="ignore").read()


def title_of(p, s):
    m = TITLE_RX.search(s)
    t = html.unescape(m.group(1)).strip() if m else p
    return re.sub(r"\s*\|\s*(FinanceRateCalc|FRC)\s*$", "", t)


def figure_of(s):
    m = DESC_RX.search(s)
    if not m:
        return ""
    d = html.unescape(m.group(1))
    f = re.search(r"\b\d{1,2}\.\d%\b", d)
    return f.group(0) if f else ""


def page(title, kicker, body, canonical, desc):
    return (f'<!DOCTYPE html>\n<html lang="en"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
            f"<title>{html.escape(title)} | FinanceRateCalc</title>\n<meta name=\"description\" content=\"{html.escape(desc)}\">\n"
            f'<link rel="canonical" href="https://financeratecalc.com/{canonical}">\n<style>{STYLE}</style></head>\n<body>\n{NAV}\n<div class="wrap">\n'
            f'<div class="kicker">{kicker}</div>\n<h1>{html.escape(title)}</h1>\n{body}\n'
            '<p class="small">Generated by <code>scripts/build_site_index.py</code> from the pages themselves; a figure shown here is the one in that page\'s own description. Nothing on this page is advice about any loan.</p>\n'
            "</div>\n</body></html>\n")


def li(p, t, fig=""):
    return f'<li><a href="/{p}">{html.escape(t)}</a>{(" — " + fig) if fig else ""}</li>'


def main():
    check = "--check" in sys.argv
    out = {}
    pages = {}
    for p in sorted(glob.glob("**/*.html", recursive=True)):
        # generated pages are not sources of links (otherwise the orphan list would empty itself on the second run)
        if p.startswith(SKIP_DIRS) or (os.path.basename(p) == "index.html" and p != "index.html") or p == "site-index.html":
            continue
        s = read(p)
        pages[p] = s
    # metro
    by_state = defaultdict(list)
    for p, s in pages.items():
        if not p.startswith("metro/"):
            continue
        st = re.search(r"-([a-z]{2}(?:-[a-z]{2}){0,3})\.html$", p)
        key = st.group(1).upper().replace("-", "–") if st else "Other"
        by_state[key.split("–")[0]].append((p, title_of(p, s), figure_of(s)))
    body = ["<p>Every metro page on the site, grouped by the first state in the metro name. Two page families exist: <i>FHA Denial Rate: …</i> (the metro figure with its receipt) and <i>FHA Denial Rates by Lender in …</i> (the lender table for that metro). Hub: <a href=\"/fha-denial-rates-by-metro.html\">metro overview</a>.</p>"]
    for st in sorted(by_state):
        body.append(f"<h2>{st}</h2><ul>" + "".join(li(*x) for x in sorted(by_state[st], key=lambda x: x[1])) + "</ul>")
    out["metro/index.html"] = page(f"All {sum(len(v) for v in by_state.values())} metro pages", "FinanceRateCalc · index · metros", "\n".join(body),
                                   "metro/index.html", "Index of every FHA denial-rate metro page on FinanceRateCalc, grouped by state, 2025 HMDA record.")
    # stat and city
    for d, ttl, desc, intro in (("stat", "All question pages", "Index of every question-form statistics page on FinanceRateCalc.", "Short pages, one question each, answered from the 2025 HMDA record with a receipt."),
                                ("city", "All city affordability pages", "Index of every city housing-affordability page on FinanceRateCalc.", "City pages from the affordability series; each carries its receipt.")):
        items = [(p, title_of(p, s), "") for p, s in pages.items() if p.startswith(d + "/")]
        out[f"{d}/index.html"] = page(f"{ttl} ({len(items)})", f"FinanceRateCalc · index · {d}", f"<p>{intro}</p><ul>" + "".join(li(*x) for x in sorted(items, key=lambda x: x[1])) + "</ul>",
                                      f"{d}/index.html", desc)
    # site index: hubs + every page with no incoming link from any other page
    inl = defaultdict(int)
    for p, s in pages.items():
        for h in set(HREF_RX.findall(s)):
            if h != p:
                inl[h] += 1
    hubs = [("fha-denial-rates-by-state.html", "States"), ("fha-denial-rates-by-metro.html", "Metros"), ("metro/index.html", "All metro pages"),
            ("fha-denial-rates-top-100.html", "Lenders (top 100)"), ("fha-denial-rates-by-loan-amount.html", "Loan amount (small-loan penalty)"),
            ("answers.html", "Answers"), ("stat/index.html", "All question pages"), ("city/index.html", "All city pages"),
            ("why-fha-denial-rates-differ.html", "Why are there several FHA denial rates?"), ("claims/", "Claims (386 receipts)"),
            ("corrections.html", "Corrections log"), ("methodology.html", "Methodology"), ("mcp-server.html", "MCP evidence server"),
            ("check-answer.html", "Check an answer"), ("verify.html", "Verify a receipt"), ("data.html", "Data downloads")]
    orphans = [(p, title_of(p, s)) for p, s in pages.items()
               if inl[p] == 0 and not NOINDEX_RX.search(s) and not p.startswith(("metro/", "stat/", "city/")) and p != "index.html" and p != "site-index.html"]
    body = ["<p>Hubs first, then every indexable page that no other page links to. Crawlers reach these through the sitemaps and <a href=\"/llms.txt\">llms.txt</a>; this page gives readers the same door.</p>",
            "<h2>Hubs</h2><ul>" + "".join(f'<li><a href="/{h}">{html.escape(t)}</a></li>' for h, t in hubs) + "</ul>"]
    if orphans:
        body.append(f"<h2>Pages not linked from elsewhere ({len(orphans)})</h2><ul>" + "".join(li(p, t) for p, t in sorted(orphans, key=lambda x: x[1])) + "</ul>")
    out["site-index.html"] = page("Site index", "FinanceRateCalc · index", "\n".join(body), "site-index.html",
                                  "Index of FinanceRateCalc hubs and of every page not linked from another page.")
    changed = []
    for p, s in out.items():
        cur = read(p) if os.path.exists(p) else None
        if cur != s:
            changed.append(p)
            if not check:
                os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
                open(p, "w", encoding="utf-8").write(s)
    print(f"site index: {len(by_state)} states, {sum(len(v) for v in by_state.values())} metro, {len(orphans)} orphan pages listed; changed: {changed or 'none'}")
    if check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
